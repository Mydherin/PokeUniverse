-- +goose Up
-- The bag (Phase 4): each pocket's items in the player's order (one slot per item, by FireRed's
-- item ID), and what items keep besides: SELECT's registered item, REPEL steps left, the
-- WHITE/BLACK FLUTE in effect, coins and berry powder.
CREATE TABLE trainer_items (
    account_id bigint   NOT NULL REFERENCES trainers (account_id) ON DELETE CASCADE,
    pocket     smallint NOT NULL CHECK (pocket BETWEEN 1 AND 5),
    slot       smallint NOT NULL CHECK (slot >= 0),
    item       smallint NOT NULL CHECK (item > 0),
    quantity   smallint NOT NULL CHECK (quantity BETWEEN 1 AND 999),
    PRIMARY KEY (account_id, pocket, slot),
    UNIQUE (account_id, item)
);

ALTER TABLE trainers
    ADD COLUMN registered_item smallint NOT NULL DEFAULT 0,
    ADD COLUMN repel_steps     smallint NOT NULL DEFAULT 0 CHECK (repel_steps >= 0),
    ADD COLUMN flute           text     NOT NULL DEFAULT 'none' CHECK (flute IN ('none', 'white', 'black')),
    ADD COLUMN coins           integer  NOT NULL DEFAULT 0 CHECK (coins BETWEEN 0 AND 9999),
    ADD COLUMN berry_powder    integer  NOT NULL DEFAULT 0 CHECK (berry_powder BETWEEN 0 AND 99999);

